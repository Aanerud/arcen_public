    #[test]
    fn a_desktop_is_admitted_only_when_polkit_refuses_its_session() {
        use Admission::{Admit, Refuse};
        use DesktopSeat::{ArcenSeat, ConsoleSeat, Seatless};
        use PolkitState::RuleInstalled;
        for state in [
            RuleInstalled,
            PolkitState::Unknown,
            PolkitState::RuleMissing,
        ] {
            assert_eq!(
                admission(state, Seatless, &[]),
                Admission::AdmitUnverified,
                "a seatless desktop is never refused for polkit's tools"
            );
            assert_eq!(
                admission(state, Seatless, &[check(2), check(127)]),
                Admission::AdmitUnverified
            );
            assert_eq!(
                admission(state, Seatless, &[check(0)]),
                Refuse(PolkitUnprotected::Granted)
            );
        }
        for seat in [ConsoleSeat, ArcenSeat] {
            assert_eq!(admission(RuleInstalled, seat, &[check(2), check(1)]), Admit);
            assert_eq!(admission(RuleInstalled, seat, &[check(3)]), Admit);
            assert_eq!(
                admission(RuleInstalled, seat, &[check(2), check(0)]),
                Refuse(PolkitUnprotected::Granted)
            );
            assert_eq!(
                admission(RuleInstalled, seat, &[]),
                Refuse(PolkitUnprotected::Unverified),
                "nothing asked proves nothing"
            );
            assert_eq!(
                admission(RuleInstalled, seat, &[check(2), check(127)]),
                Refuse(PolkitUnprotected::Unverified)
            );
            assert_eq!(
                admission(PolkitState::Unknown, seat, &[]),
                Refuse(PolkitUnprotected::Unverified)
            );
            assert_eq!(admission(PolkitState::Absent, seat, &[]), Admit);
        }
    }

