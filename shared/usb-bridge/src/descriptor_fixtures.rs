//! Illustrative HID report descriptors shared by tests across crates.
//!
//! These are written for Arcen's tests, not captured from devices. They
//! reproduce *structure* — which top-level collections a device publishes on
//! which usage pages — because that is what classification depends on. Vendor
//! and model names are informational labels only.

/// Interface 0 of an Intuos5-style tablet (`056a:0317` publishes this shape):
/// one application collection on the vendor-defined Digitizers page `0xFF0D`
/// with usage Digitizer (`0x01`), whose pen reports and feature reports are
/// opaque vendor bytes. Nothing in it names pressure, tilt or position, so a
/// classifier must not claim them.
pub const INTUOS5_STYLE_PEN_INTERFACE: &[u8] = &[
    0x06, 0x0D, 0xFF, // Usage Page (vendor-defined Digitizers, 0xFF0D)
    0x09, 0x01, // Usage (Digitizer)
    0xA1, 0x01, // Collection (Application)
    0x85, 0x02, //   Report ID (2): pen
    0x09, 0x00, //   Usage (undefined)
    0x15, 0x00, //   Logical Minimum (0)
    0x26, 0xFF, 0x00, //   Logical Maximum (255)
    0x75, 0x08, //   Report Size (8)
    0x95, 0x09, //   Report Count (9)
    0x81, 0x02, //   Input (Data,Var,Abs) — opaque pen report
    0x85, 0x03, //   Report ID (3)
    0x09, 0x00, //   Usage (undefined)
    0x95, 0x09, //   Report Count (9)
    0x81, 0x02, //   Input — opaque
    0x85, 0x02, //   Report ID (2)
    0x09, 0x00, //   Usage (undefined)
    0x95, 0x01, //   Report Count (1)
    0xB1, 0x02, //   Feature — mode switch
    0x85, 0x03, //   Report ID (3)
    0x09, 0x00, //   Usage (undefined)
    0x95, 0x01, //   Report Count (1)
    0xB1, 0x02, //   Feature
    0x85, 0x04, //   Report ID (4)
    0x09, 0x00, //   Usage (undefined)
    0x95, 0x0F, //   Report Count (15)
    0xB1, 0x02, //   Feature
    0xC0, // End Collection
];

